// Builds src/icons/icons.ts from the brand icon set in images/icons (24x24, 2px stroke).
// Run with `pnpm icons` after adding or changing an icon.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, "../../../images/icons");
const outFile = join(here, "../src/icons/icons.ts");

const entries = readdirSync(srcDir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    const svg = readFileSync(join(srcDir, f), "utf8");
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .trim();
    return `  ${JSON.stringify(f.replace(/\.svg$/, ""))}: ${JSON.stringify(inner)},`;
  });

writeFileSync(
  outFile,
  `// Generated by scripts/build-icons.mjs from images/icons. Do not edit by hand.\n\nexport const icons = {\n${entries.join("\n")}\n} as const;\n\nexport type IconName = keyof typeof icons;\n`
);
console.log(`Wrote ${entries.length} icons to ${outFile}`);
